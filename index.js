// يحسب تكلفة مجموعة توكن بالدينار الكويتي
function tokensCostKWD(inTok, outTok, cacheWrite, cacheRead) {
  const usd = (
    (inTok || 0) * PRICE_INPUT +
    (outTok || 0) * PRICE_OUTPUT +
    (cacheWrite || 0) * PRICE_CACHE_WRITE +
    (cacheRead || 0) * PRICE_CACHE_READ
  ) / 1_000_000;
  return usd * USD_TO_KWD;
}

